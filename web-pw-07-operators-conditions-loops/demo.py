"""Runs every task with sample keyboard input and writes the results to demo_output.md.

Usage: python3 demo.py
"""
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
# Runs a task like in a terminal: whatever is "typed" is echoed after the prompt.
ECHO = ("import builtins, runpy, sys\n"
        "read = builtins.input\n"
        "def typed(prompt=''):\n"
        "    value = read(prompt)\n"
        "    print(value)\n"
        "    return value\n"
        "builtins.input = typed\n"
        "sys.path.insert(0, sys.argv[1])\n"
        "runpy.run_path(sys.argv[2], run_name='__main__')\n")
RUNS = [
    ("Task 1. Even or Odd Number", "task01_even_odd.py", ["14", "-7"]),
    ("Task 2. Exam Admission", "task02_exam_admission.py", ["85\nyes", "65\nyes", "90\nno"]),
    ("Task 3. Student Grade Calculator", "task03_grade_calculator.py", ["95", "80", "60", "30", "120"]),
    ("Task 4. Discount Calculator", "task04_discount.py", ["8000", "25000", "60000", "150000"]),
    ("Task 5. Day of the Week", "task05_day_of_week.py", ["1", "7", "9"]),
    ("Task 6. Numbers from 1 to N", "task06_numbers_1_to_n.py", ["5"]),
    ("Task 7. Sum of Numbers", "task07_sum_while.py", ["10"]),
    ("Task 8. Multiplication Table", "task08_multiplication_table.py", ["5"]),
    ("Task 9. Password Verification", "task09_password.py", ["1234\nadmin\njava123"]),
    ("Task 10. ATM Simulator", "task10_atm.py", ["1\n2\n0\n2\n20000\n3\n500000\n3\n70000\n7\n1\n4"]),
]

lines = ["# Practical Work 7 — sample runs", "",
         "Generated by `python3 demo.py`: each task is run with the input shown and its output is copied below.", ""]
for title, script, inputs in RUNS:
    lines += [f"## {title}", ""]
    for keyboard in inputs:
        out = subprocess.run([sys.executable, "-c", ECHO, str(HERE / "tasks"), str(HERE / "tasks" / script)],
                             input=keyboard + "\n",
                             capture_output=True, text=True, timeout=10).stdout
        shown = keyboard.replace("\n", " ⏎ ")
        lines += [f"Input: `{shown}`", "", "```text", out.rstrip(), "```", ""]
(HERE / "demo_output.md").write_text("\n".join(lines), encoding="utf-8")
print("written", HERE / "demo_output.md")
